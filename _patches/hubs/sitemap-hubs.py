#!/usr/bin/env python3
"""KW:HUBS-SITEMAP (Muppet 19 Oct 2026) — teach BOTH sitemap generators about the subject hubs.

build-concept-pages.mjs and knowhere-seo-v2.sh each rebuild the /hsc/ + /vce/ rows from disk. Without this,
the first regen of either would (a) drop every hub URL and (b) list hsc/biology/index.html as a concept page
called /hsc/biology/index. After it, both emit hubs as /hsc/biology/ (a hub row is kept verbatim if already
there, so lastmod does not churn), skip index.html as a concept, and order rows site → hubs → concepts,
the same order build-hub-pages.mjs writes. The concept generator also learns to say how many of the pages
it would build are byte-identical to disk (so a dry run shows what a regen would really change).

  python3 _patches/hubs/sitemap-hubs.py            # dry run
  python3 _patches/hubs/sitemap-hubs.py --apply    # backups -> _patches/hubs/bak-sitemap-<ts>/
"""
import os, sys, shutil, datetime
APPLY = "--apply" in sys.argv
assert os.path.exists("build-concept-pages.mjs") and os.path.exists("knowhere-seo-v2.sh"), "run from the repo root"
TS = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
BAK = os.path.join("_patches", "hubs", f"bak-sitemap-{TS}")

JS = "build-concept-pages.mjs"
JS_EDITS = [
  # 1. concept walk skips hub index.html (Year 11 branch, then the plain branch)
  ("for (const f of fs.readdirSync(sd)) if (f.endsWith('.html')) onDisk.add(path.join(sd, f)); } continue; }",
   "for (const f of fs.readdirSync(sd)) if (f.endsWith('.html') && f !== 'index.html') onDisk.add(path.join(sd, f)); } continue; }"),
  ("    for (const f of fs.readdirSync(dir)) if (f.endsWith('.html')) onDisk.add(path.join(cert, d, f));",
   "    for (const f of fs.readdirSync(dir)) if (f.endsWith('.html') && f !== 'index.html') onDisk.add(path.join(cert, d, f));  /* index.html = a subject hub (build-hub-pages.mjs) */"),
  # 2. sitemap keeps / emits the hub rows
  ("  const rows = files.map(f => `  <url><loc>https://knowhere.me/${f.replace(/\\.html$/, '')}</loc><lastmod>${today}</lastmod><priority>0.7</priority></url>`);\n"
   "  return '<?xml version=\"1.0\" encoding=\"UTF-8\"?>\\n<urlset xmlns=\"http://www.sitemaps.org/schemas/sitemap/0.9\">\\n' + [...keep, ...rows].join('\\n') + '\\n</urlset>\\n';",
   "  const rows = files.map(f => `  <url><loc>https://knowhere.me/${f.replace(/\\.html$/, '')}</loc><lastmod>${today}</lastmod><priority>0.7</priority></url>`);\n"
   "  /* KW:HUBS-SITEMAP 19 Oct 2026 — subject hubs (build-hub-pages.mjs) are rows too: /hsc/, /hsc/biology/ … An existing hub row is\n"
   "     kept verbatim so a concept regen does not churn its lastmod; a hub on disk with no row gets one. */\n"
   "  const oldHub = new Map(xml.split('\\n').filter(l => /<loc>https:\\/\\/knowhere\\.me\\/(hsc|vce)\\/([^<]*\\/)?<\\/loc>/.test(l)).map(l => [l.match(/<loc>([^<]*)<\\/loc>/)[1], l]));\n"
   "  const hubDirs = [];\n"
   "  const walkHubs = d => { if (!fs.existsSync(d)) return; if (fs.existsSync(path.join(d, 'index.html'))) hubDirs.push(d); for (const s of fs.readdirSync(d)) if (fs.statSync(path.join(d, s)).isDirectory()) walkHubs(path.join(d, s)); };\n"
   "  walkHubs('hsc'); walkHubs('vce');\n"
   "  const hubRows = hubDirs.map(d => `https://knowhere.me/${d.split(path.sep).join('/')}/`).sort()\n"
   "    .map(u => oldHub.get(u) || `  <url><loc>${u}</loc><lastmod>${today}</lastmod><priority>${u.split('/').length <= 5 ? '0.8' : '0.7'}</priority></url>`);\n"
   "  return '<?xml version=\"1.0\" encoding=\"UTF-8\"?>\\n<urlset xmlns=\"http://www.sitemaps.org/schemas/sitemap/0.9\">\\n' + [...keep, ...hubRows, ...rows].join('\\n') + '\\n</urlset>\\n';"),
  # 3. dry-run honesty: how many built pages are byte-identical to what is on disk
  ("if (!APPLY) { console.log('\\nnothing written — re-run with --apply'); process.exit(0); }",
   "{ const same = built.filter(b => fs.existsSync(b.p.file) && fs.readFileSync(b.p.file, 'utf8') === b.html).length;\n"
   "  console.log(`pages identical to disk: ${same}/${built.length}${same < built.length ? ' — the rest would change on --apply' : ''}`); }\n"
   "if (!APPLY) { console.log('\\nnothing written — re-run with --apply'); process.exit(0); }"),
]

PY = "knowhere-seo-v2.sh"
PY_EDITS = [
  ("                    for f in sorted(os.listdir(d2)):\n                        if not f.endswith(\".html\") or \".bak\" in f: continue\n",
   "                    for f in sorted(os.listdir(d2)):\n                        if not f.endswith(\".html\") or \".bak\" in f or f == \"index.html\": continue\n"),
  ("            for f in sorted(os.listdir(d)):\n                if not f.endswith(\".html\") or \".bak\" in f: continue\n",
   "            for f in sorted(os.listdir(d)):\n                if not f.endswith(\".html\") or \".bak\" in f or f == \"index.html\": continue  # index.html = subject hub\n"),
  ("    # KW:CONCEPT 17 Sep 2026 — the concept pages (/hsc/..., /vce/...) are generated by build-concept-pages.mjs\n",
   "    # KW:HUBS-SITEMAP 19 Oct 2026 — subject hubs (build-hub-pages.mjs): /hsc/, /hsc/biology/ ... before the concept rows.\n"
   "    # An existing hub row is kept verbatim (no lastmod churn); a hub on disk with no row gets one.\n"
   "    _old = open(os.path.join(ROOT, \"sitemap.xml\"), encoding=\"utf-8\").read().split(\"\\n\")\n"
   "    _oldhub = {re.search(r\"<loc>([^<]*)</loc>\", l).group(1): l for l in _old if re.search(r\"<loc>https://knowhere\\.me/(hsc|vce)/([^<]*/)?</loc>\", l)}\n"
   "    _hubs = []\n"
   "    for cert in (\"hsc\", \"vce\"):\n"
   "        for dp, dn, fn in os.walk(os.path.join(ROOT, cert)):\n"
   "            if \"index.html\" in fn: _hubs.append(SITE + \"/\" + os.path.relpath(dp, ROOT).replace(os.sep, \"/\") + \"/\")\n"
   "    for u in sorted(_hubs):\n"
   "        rows.append(_oldhub.get(u) or f\"  <url><loc>{u}</loc><lastmod>{TODAY}</lastmod><priority>{'0.8' if u.count('/') <= 4 else '0.7'}</priority></url>\")\n"
   "    # KW:CONCEPT 17 Sep 2026 — the concept pages (/hsc/..., /vce/...) are generated by build-concept-pages.mjs\n"),
]

def run(path, edits):
    s = open(path, encoding="utf-8").read(); n = s
    for old, new in edits:
        if new in n: continue
        assert n.count(old) == 1, (path, old[:80], n.count(old))
        n = n.replace(old, new, 1)
    return s, n

plan = [(p,) + run(p, e) for p, e in ((JS, JS_EDITS), (PY, PY_EDITS))]
for p, s, n in plan: print(f"{p}: {'change' if n != s else 'already done'}")
if not APPLY: print("\nDRY RUN — nothing written."); sys.exit(0)
for p, s, n in plan:
    if n == s: continue
    os.makedirs(BAK, exist_ok=True); shutil.copy2(p, os.path.join(BAK, p))
    open(p, "w", encoding="utf-8").write(n)
    assert open(p, encoding="utf-8").read() == n
print(f"WRITTEN · backups in {BAK}")
